"""Build the detail material sets of the terrain renderer.

    python -I tools/terrain/gen_materials.py [--set earth-volcanic-coast|lunar-regolith] [--preview] [--manifest-only]

--manifest-only rewrites set.json (weights and gains) and keeps the textures and their statistics.

A material has four texture layers with DIFFERENT content, one per detail scale: near (2 m of ground,
1024 px), mid (14 m, 512 px), far (110 m, 512 px) and aerial (900 m, 512 px). Per layer two RGBA WebP files:
  <id>-<scale>.ah.webp    rgb = sRGB albedo, a = height (0..1 over the layer's relief; lunar-regolith: height above
                          the surroundings, so that pits and stones stand out from a level mean)
  <id>-<scale>.nra.webp   rg = tangent-space normal xy (0.5 = flat; true slopes of the layer at its ground size),
                          b = perceptual roughness, a = ambient occlusion
plus public/assets/terrain/<set>/set.json and, with --preview, lit contact sheets under out/terrain/materials/.

earth-volcanic-coast is PHOTOGRAPHIC: the albedo of every layer comes from a top-down photograph generated by
tools/terrain/photo_source.py (data/cache/terrain/photo/<material>-<scale>-0.png, not committed). This script
removes the residual large-scale shading, makes the image tile (two minimum-error seams per axis between the
image and itself shifted by half, blended in two frequency bands), and derives height, normal, roughness and
occlusion from it. lunar-regolith is synthesised from periodic height fields (grain, clods, pebbles, pits and
craters with real relief, in the numbers of the equilibrium population the height authority uses):
photographs of the lunar surface carry hard shadows of one sun direction, which a renderer that lights the
ground itself cannot use. Its fourth material, "boulder", is the fractured face of a rock; only the rock
meshes carry it.

Albedos are physically plausible linear reflectances (basalt 0.04-0.07, dry soil about 0.14, grass about
0.08, weathered concrete about 0.3, lunar regolith about 0.12). The renderer multiplies the imagery by
albedo / mean albedo of the layer, so on natural ground only structure and relative colour reach the screen.
"""
