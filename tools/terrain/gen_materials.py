def spectral(n: int, seed: int, beta: float, lo: float = 1.0, hi: float | None = None, aniso: tuple[float, float] = (1.0, 1.0)) -> np.ndarray:
    """Periodic random field with power spectrum f^-beta between `lo` and `hi` cycles per tile; zero mean, unit std."""
    rng = np.random.default_rng(seed)
    fx = np.fft.fftfreq(n, 1.0 / n)[None, :] * aniso[0]
    fy = np.fft.fftfreq(n, 1.0 / n)[:, None] * aniso[1]
    f = np.sqrt(fx * fx + fy * fy)
    amp = np.zeros_like(f)
    band = f >= lo
    if hi is not None:
        band &= f <= hi
    amp[band] = f[band] ** (-beta / 2.0)
    phase = rng.uniform(0.0, 2.0 * np.pi, (n, n))
    field = np.fft.ifft2(amp * np.exp(1j * phase)).real
    field -= field.mean()
    return field / (field.std() + 1e-12)


def gauss(a: np.ndarray, sigma: float) -> np.ndarray:
    """Periodic Gaussian blur (sigma in pixels) of a 2-D field or of every channel of an image."""
    if a.ndim == 3:
        return np.stack([gauss(a[..., c], sigma) for c in range(a.shape[2])], -1)
    h, w = a.shape
    fx = np.fft.fftfreq(w)[None, :]
    fy = np.fft.fftfreq(h)[:, None]
    k = np.exp(-2.0 * (np.pi * sigma) ** 2 * (fx * fx + fy * fy))
    return np.fft.ifft2(np.fft.fft2(a) * k).real


def worley(n: int, count: int, seed: int, jitter: float = 1.0) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Cellular noise on a torus: F1, F2 (in units of the mean point spacing), cell index, and the points."""
    rng = np.random.default_rng(seed)
    g = int(np.ceil(np.sqrt(count)))
    cells = np.stack(np.meshgrid(np.arange(g), np.arange(g), indexing="xy"), -1).reshape(-1, 2).astype(np.float64)
    pts = (cells + 0.5 + (rng.uniform(-0.5, 0.5, cells.shape)) * jitter) / g
    tiled = np.concatenate([pts + np.array([dx, dy]) for dx in (-1, 0, 1) for dy in (-1, 0, 1)])
    tree = cKDTree(tiled)
    ys, xs = np.mgrid[0:n, 0:n]
    q = np.stack([(xs + 0.5) / n, (ys + 0.5) / n], -1).reshape(-1, 2)
    d, idx = tree.query(q, k=2)
    spacing = 1.0 / g
    f1 = (d[:, 0] / spacing).reshape(n, n)
    f2 = (d[:, 1] / spacing).reshape(n, n)
    ids = (idx[:, 0] % len(pts)).reshape(n, n)
    return f1, f2, ids, pts


def smoothstep(e0: float, e1: float, x: np.ndarray) -> np.ndarray:
    t = np.clip((x - e0) / (e1 - e0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def unit(a: np.ndarray) -> np.ndarray:
    lo, hi = np.percentile(a, 0.5), np.percentile(a, 99.5)
    return np.clip((a - lo) / (hi - lo + 1e-12), 0.0, 1.0)


def cell_random(ids: np.ndarray, seed: int) -> np.ndarray:
    """One uniform random number per cell of a cellular field."""
    rng = np.random.default_rng(seed)
    return rng.uniform(0.0, 1.0, int(ids.max()) + 1)[ids]


def linear_to_srgb(c: np.ndarray) -> np.ndarray:
    return np.where(c <= 0.0031308, c * 12.92, 1.055 * np.power(np.maximum(c, 1e-9), 1.0 / 2.4) - 0.055)


def srgb_to_linear(c: np.ndarray) -> np.ndarray:
    return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)


def luminance(rgb: np.ndarray) -> np.ndarray:
    return rgb[..., 0] * 0.2126 + rgb[..., 1] * 0.7152 + rgb[..., 2] * 0.0722


def stamp(height: np.ndarray, cx: float, cy: float, radius: float, profile, extent: float = 1.0) -> None:
    """Add profile(dx / radius, dy / radius) to a periodic height field around (cx, cy) (pixels), out to extent x radius."""
    n = height.shape[0]
    reach = int(np.ceil(radius * extent)) + 1
    xs = np.arange(int(np.floor(cx)) - reach, int(np.floor(cx)) + reach + 1)
    ys = np.arange(int(np.floor(cy)) - reach, int(np.floor(cy)) + reach + 1)
    dx = np.broadcast_to((xs + 0.5 - cx)[None, :] / radius, (len(ys), len(xs)))
    dy = np.broadcast_to((ys + 0.5 - cy)[:, None] / radius, (len(ys), len(xs)))
    add = np.where(dx * dx + dy * dy < extent * extent, profile(dx, dy), 0.0)
    np.add.at(height, (ys[:, None] % n, xs[None, :] % n), add)


def crater_profile(depth: float, rim: float, fresh: float):
    """A crater in a state of wear. Fresh (1): a parabolic bowl, -depth at the centre, up to a crest of +rim
    at r = 1 that falls off as r^-3 outside. Worn (0): the same volume smoothed by its age: a rimless
    Gaussian hollow with soft edges. Between: the mix. (No flat floor at any age: a small crater is a bowl.)"""
    def f(dx: np.ndarray, dy: np.ndarray) -> np.ndarray:
        x = np.sqrt(dx * dx + dy * dy)
        inside = rim - (depth + rim) * (1.0 - np.clip(x, 0, 1) ** 2.0)
        sharp = np.where(x < 1.0, inside, rim * np.maximum(x, 1.0) ** -3.0)
        soft = -depth * np.exp(-((x / 0.62) ** 2.0))
        return fresh * sharp + (1.0 - fresh) * soft
    return f


def polygon_metric(rng: np.random.Generator, angular: float):
    """Distance measure whose unit ball is a random convex polygon (angular = 1) or the unit disc (angular = 0)."""
    k = int(rng.integers(4, 7))
    ang = (np.arange(k) + rng.uniform(-0.3, 0.3, k)) / k * 2 * np.pi + rng.uniform(0, 2 * np.pi)
    reach = rng.uniform(0.55, 1.0, k)
    stretch = rng.uniform(1.0, 1.7)
    turn = rng.uniform(0, np.pi)

    def f(dx: np.ndarray, dy: np.ndarray) -> np.ndarray:
        u = (dx * np.cos(turn) + dy * np.sin(turn)) * stretch
        v = -dx * np.sin(turn) + dy * np.cos(turn)
        poly = np.full(dx.shape, 0.0)
        for a, r in zip(ang, reach):
            poly = np.maximum(poly, (u * np.cos(a) + v * np.sin(a)) / r)
        disc = np.sqrt(u * u + v * v)
        return angular * poly + (1.0 - angular) * disc
    return f


def power_law_sizes(rng: np.random.Generator, count: int, lo: float, hi: float, exponent: float) -> np.ndarray:
    """`count` sizes between lo and hi with a cumulative distribution N(>D) ~ D^-exponent."""
    u = rng.uniform(0.0, 1.0, count)
    return (lo ** -exponent - u * (lo ** -exponent - hi ** -exponent)) ** (-1.0 / exponent)


# ---------------------------------------------------------------------------------------------- layers

class Layer:
    """A finished layer: height in metres, linear albedo (n, n, 3), roughness; `metres` = ground size of the tile."""

    def __init__(self, metres: float, height_m: np.ndarray, albedo: np.ndarray, roughness: np.ndarray, ao_gain: float = 1.0):
        self.metres = metres
        self.height_m = height_m - height_m.min()
        self.albedo = np.clip(albedo, 0.0, 1.0)
        self.roughness = np.clip(roughness, 0.05, 1.0)
        self.ao_gain = ao_gain
        self.feature_sigma: float | None = None

    def slopes(self) -> tuple[np.ndarray, np.ndarray]:
        n = self.height_m.shape[0]
        k = n / self.metres
        gx = (np.roll(self.height_m, -1, 1) - np.roll(self.height_m, 1, 1)) * 0.5 * k
        gy = (np.roll(self.height_m, -1, 0) - np.roll(self.height_m, 1, 0)) * 0.5 * k
        return gx, gy

    def rms_slope(self) -> float:
        gx, gy = self.slopes()
        return float(np.sqrt((gx * gx + gy * gy).mean()))

    def scaled_to_slope(self, rms: float) -> "Layer":
        self.height_m = self.height_m * (rms / (self.rms_slope() + 1e-12))
        return self

    def with_feature_height(self, sigma_px: float) -> "Layer":
        """Store in the height channel the height above the surroundings (what is left after removing a
        Gaussian of sigma_px), not the height itself: the channel decides which copy of the layer and which
        material shows, and there a pit on a rise must still count as a pit. Normals keep the true slopes."""
        self.feature_sigma = sigma_px
        return self

    def blend_height(self) -> np.ndarray:
        h = self.height_m if self.feature_sigma is None else self.height_m - gauss(self.height_m, self.feature_sigma)
        return h - h.min()


# ------------------------------------------------------------------------------ photographic (Earth) layers

def load_photo(name: str) -> np.ndarray:
    path = os.path.join(PHOTO_DIR, f"{name}-0.png")
    if not os.path.exists(path):
        raise SystemExit(f"missing source photograph {path}: run python -I tools/terrain/photo_source.py --only {name}")
    img = np.asarray(Image.open(path).convert("RGB"), np.float64) / 255.0
    if img.shape[0] != img.shape[1]:
        raise SystemExit(f"{path}: not square")
    return srgb_to_linear(img)


def delight(img: np.ndarray, sigma_frac: float) -> np.ndarray:
    """Divide out brightness variations longer than about sigma_frac of the frame (uneven lighting, vignetting)."""
    n = img.shape[0]
    sigma = n * sigma_frac
    lum = np.log(luminance(img) + 1e-4)
    low = ndimage.gaussian_filter(lum, sigma, mode="reflect")
    out = img * np.exp(-(low - low.mean()))[..., None]
    # Slow colour drifts go the same way, at half strength.
    for c in range(3):
        ch = np.log(out[..., c] + 1e-4)
        lowc = ndimage.gaussian_filter(ch, sigma, mode="reflect")
        out[..., c] = out[..., c] * np.exp(-0.5 * (lowc - lowc.mean()))
    return out


def min_seam(cost: np.ndarray, closed: bool) -> np.ndarray:
    """Column index per row of the cheapest top-to-bottom path through `cost` (steps of at most one column).
    closed: the path ends in the column it starts in (the image is periodic along the path)."""
    h, w = cost.shape
    c = cost.copy()
    if closed:
        anchor = int(np.argmin(cost.sum(0)))
        block = np.ones(w, bool)
        block[anchor] = False
        c[0, block] = np.inf
        c[h - 1, block] = np.inf
    acc = np.empty_like(c)
    acc[0] = c[0]
    for y in range(1, h):
        prev = acc[y - 1]
        left = np.concatenate(([np.inf], prev[:-1]))
        right = np.concatenate((prev[1:], [np.inf]))
        acc[y] = c[y] + np.minimum(prev, np.minimum(left, right))
    path = np.empty(h, np.int64)
    path[h - 1] = int(np.argmin(acc[h - 1]))
    for y in range(h - 2, -1, -1):
        x = path[y + 1]
        lo, hi = max(0, x - 1), min(w - 1, x + 1)
        path[y] = lo + int(np.argmin(acc[y, lo : hi + 1]))
    return path


def make_periodic_x(img: np.ndarray, y_periodic: bool) -> np.ndarray:
    """Make an image tile along x. The image shifted by half a width is continuous across the border; the
    original is continuous in the middle. The result takes the shifted image near the border and the original
    in the middle, switching along two minimum-error seams, low frequencies blended wide, detail narrow."""
    n = img.shape[1]
    shifted = np.roll(img, n // 2, axis=1)
    diff = ((img - shifted) ** 2).sum(-1)
    diff = ndimage.uniform_filter(diff, 5, mode="nearest") + 1e-6
    mask = np.zeros(img.shape[:2])
    a0, a1 = n // 8, 3 * n // 8
    b0, b1 = 5 * n // 8, 7 * n // 8
    left = a0 + min_seam(diff[:, a0:a1], y_periodic)
    right = b0 + min_seam(diff[:, b0:b1], y_periodic)
    xs = np.arange(n)[None, :]
    mask[(xs >= left[:, None]) & (xs < right[:, None])] = 1.0
    modes = ("wrap" if y_periodic else "reflect", "reflect")
    blur = lambda a, s: ndimage.gaussian_filter(a, (s, s) + (0,) * (a.ndim - 2), mode=modes + ("nearest",) * (a.ndim - 2))  # noqa: E731
    low_a, low_b = blur(img, 12.0), blur(shifted, 12.0)
    wide = blur(mask, 16.0)[..., None]
    narrow = blur(mask, 1.2)[..., None]
    return (low_a * wide + low_b * (1 - wide)) + ((img - low_a) * narrow + (shifted - low_b) * (1 - narrow))


def make_tileable(img: np.ndarray) -> np.ndarray:
    step1 = make_periodic_x(img, False)
    # Along y: the same on the transposed image, whose seams must now close (the image is periodic along them).
    step2 = make_periodic_x(np.transpose(step1, (1, 0, 2)), True)
    return np.clip(np.transpose(step2, (1, 0, 2)), 0.0, 1.0)


def seam_report(img: np.ndarray) -> float:
    """Mean absolute step across the wrap divided by the mean step between neighbouring rows / columns inside."""
    lum = luminance(img)
    inner = 0.5 * (np.abs(np.diff(lum, axis=0)).mean() + np.abs(np.diff(lum, axis=1)).mean())
    wrap = 0.5 * (np.abs(lum[0] - lum[-1]).mean() + np.abs(lum[:, 0] - lum[:, -1]).mean())
    return float(wrap / (inner + 1e-12))


class PhotoSpec:
    def __init__(self, mean: tuple[float, float, float], rough: float, rough_var: float, slopes: tuple[float, float, float, float], bands: tuple[float, float, float], ao_gain: float = 1.0, contrast: float = 1.0):
        self.mean = mean            # target mean linear albedo
        self.rough = rough          # mean perceptual roughness
        self.rough_var = rough_var  # brighter than average -> smoother (+) or rougher (-), per unit of log luminance
        self.slopes = slopes        # RMS slope of the near, mid, far and aerial layer
        self.bands = bands          # weight of fine / medium / coarse luminance detail in the height
        self.ao_gain = ao_gain
        self.contrast = contrast    # gain on the log-albedo variation of the photograph


# Slopes are kept low: a height derived from brightness is right about cracks, gaps and pits and wrong about
# everything a colour difference is not a height difference of, and strong relief from it reads as embossing.
PHOTO: dict[str, PhotoSpec] = {
    "pahoehoe": PhotoSpec((0.062, 0.058, 0.055), 0.72, 0.15, (0.22, 0.18, 0.09, 0.04), (0.5, 1.0, 0.9)),
    "aa": PhotoSpec((0.040, 0.034, 0.030), 0.92, 0.0, (0.50, 0.38, 0.15, 0.06), (0.7, 1.0, 0.8), ao_gain=1.5),
    "black-sand": PhotoSpec((0.052, 0.050, 0.048), 0.88, 0.0, (0.10, 0.08, 0.035, 0.015), (0.8, 0.6, 0.8)),
    "scrub-soil": PhotoSpec((0.150, 0.105, 0.072), 0.92, 0.0, (0.16, 0.13, 0.06, 0.03), (0.7, 1.0, 0.7)),
    # Dry bunch grass of a windswept coast: olive and straw (sRGB about 108, 102, 64), not a lawn.
    "pasture": PhotoSpec((0.150, 0.132, 0.052), 0.90, 0.0, (0.30, 0.14, 0.05, 0.02), (1.0, 0.8, 0.5), ao_gain=1.3),
    "concrete": PhotoSpec((0.300, 0.292, 0.276), 0.86, 0.1, (0.035, 0.012, 0.004, 0.002), (1.0, 0.5, 0.15), ao_gain=0.6),
}


def photo_layer(material: str, scale: int, metres: float) -> tuple[Layer, float]:
    spec = PHOTO[material]
    img = load_photo(f"{material}-{SCALE_NAMES[scale]}")
    if img.shape[0] != NEAR_SIZE:
        img = cv2.resize(img, (NEAR_SIZE, NEAR_SIZE), interpolation=cv2.INTER_AREA)
    # Each scale carries its own band: what is longer than a third of the frame belongs to the next scale
    # (or, for the far layer, to the imagery).
    img = delight(img, 0.22)
    img = make_tileable(img)
    seam = seam_report(img)
    n = layer_size(scale)
    if n != img.shape[0]:
        img = cv2.resize(img, (n, n), interpolation=cv2.INTER_AREA)
    # Contrast about the mean in log space, then the material's absolute albedo.
    lum = luminance(img)
    mean_log = np.log(lum + 1e-4).mean()
    if spec.contrast != 1.0:
        img = img * np.exp((spec.contrast - 1.0) * (np.log(lum + 1e-4) - mean_log))[..., None]
    img = img * (np.array(spec.mean) / img.reshape(-1, 3).mean(0))[None, None, :]
    img = np.clip(img, 0.0, 1.0)
    # Height from brightness in three bands (cracks, gaps between blades and stones, pits are dark and low).
    l = np.log(luminance(img) + 1e-4)
    s = n / 1024.0
    g1, g4, g16, g64 = gauss(l, 1.0 * s), gauss(l, 4.0 * s), gauss(l, 16.0 * s), gauss(l, 64.0 * s)
    fine, medium, coarse = g1 - g4, g4 - g16, g16 - g64
    norm = lambda a: a / (a.std() + 1e-9)  # noqa: E731
    h = spec.bands[0] * 0.35 * norm(fine) + spec.bands[1] * 0.8 * norm(medium) + spec.bands[2] * 1.6 * norm(coarse)
    rough = spec.rough - spec.rough_var * (gauss(l, 2.0 * s) - l.mean())
    layer = Layer(metres, h, img, rough, spec.ao_gain).scaled_to_slope(spec.slopes[scale])
    return layer, seam


