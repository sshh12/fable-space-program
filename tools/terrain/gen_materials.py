def tint(base: tuple[float, float, float], n: int) -> np.ndarray:
    return np.ones((n, n, 3)) * np.array(base)[None, None, :]


def scatter_craters(h: np.ndarray, metres: float, seed: int, d_lo: float, d_hi: float, coverage: float, exponent: float = 2.0,
                    fresh_power: float = 2.5) -> np.ndarray:
    """Stamp craters with diameters d_lo..d_hi (m) until they cover `coverage` of the area. Returns freshness field 0..1."""
    n = h.shape[0]
    px = n / metres
    rng = np.random.default_rng(seed)
    area = metres * metres
    fresh_field = np.zeros_like(h)
    covered = 0.0
    sizes = np.sort(power_law_sizes(rng, 20000, d_lo, d_hi, exponent))[::-1]
    # Large first (they are the old ones underneath), stopping at the wanted coverage.
    order = rng.permutation(len(sizes))
    picked: list[float] = []
    for i in order:
        d = float(sizes[i])
        if covered + np.pi * d * d / 4 > coverage * area:
            break
        covered += np.pi * d * d / 4
        picked.append(d)
    picked.sort(reverse=True)
    # Craters come in clusters and leave stretches bare: positions are drawn with a density that varies over
    # the tile (a low-frequency field), not evenly.
    crowd = unit(spectral(n, seed + 991, 2.4, 1, 5)) * 0.5 + 0.5
    for d in picked:
        fresh = float(rng.uniform(0, 1) ** fresh_power)
        # Depth / diameter 0.2 when fresh down to 0.025 when worn out, and most are worn: under a sun of 11
        # degrees a bowl deeper than about a twentieth of its width has its floor in shadow, and a field of
        # such bowls is a field of black discs; a worn crater shows a soft crescent on its sunward wall and a
        # brighter far wall. A crest only on the fresh.
        depth = d * (0.025 + 0.175 * fresh ** 1.6)
        rim = d * 0.03 * fresh * fresh
        for _ in range(8):
            cx, cy = rng.uniform(0, n), rng.uniform(0, n)
            if rng.uniform(0, 1) < 0.15 + 0.85 * crowd[int(cy) % n, int(cx) % n] ** 2:
                break
        stamp(h, cx, cy, 0.5 * d * px, crater_profile(depth, rim, fresh), 2.5)
        if fresh > 0.45:
            stamp(fresh_field, cx, cy, 0.5 * d * px, lambda dx, dy, f=fresh: f * np.exp(-((np.maximum(np.sqrt(dx * dx + dy * dy), 0.9) - 0.9) / 0.6) ** 2), 2.5)
    return np.clip(fresh_field, 0.0, 1.0)


def scatter_lumps(h: np.ndarray, metres: float, seed: int, d_lo: float, d_hi: float, coverage: float, aspect: float, angular: float) -> np.ndarray:
    """Clods and stones: rounded (angular = 0) or flat-topped, straight-sided, tilted (angular = 1) bumps. Returns their mask."""
    n = h.shape[0]
    px = n / metres
    rng = np.random.default_rng(seed)
    mask = np.zeros_like(h)
    covered = 0.0
    for d in power_law_sizes(rng, 60000, d_lo, d_hi, 2.2):
        d = float(d)
        if covered + np.pi * d * d / 4 > coverage * metres * metres:
            break
        covered += np.pi * d * d / 4
        height = d * aspect * rng.uniform(0.5, 1.0)
        cx, cy = rng.uniform(0, n), rng.uniform(0, n)
        metric = polygon_metric(rng, angular)
        tilt_a, tilt = rng.uniform(0, 2 * np.pi), 0.15 * angular * rng.uniform(0, 1)
        edge = 2.0 + 10.0 * angular

        def profile(dx: np.ndarray, dy: np.ndarray, hh=height, metric=metric, ta=tilt_a, tl=tilt, e=edge) -> np.ndarray:
            m = metric(dx, dy)
            top = 1.0 + tl * (dx * np.cos(ta) + dy * np.sin(ta))
            return hh * top * np.clip(1.0 - m ** e, 0.0, 1.0) ** (1.0 / (1.0 + 1.5 * angular))

        stamp(h, cx, cy, 0.5 * d * px, profile, 1.9)
        stamp(mask, cx, cy, 0.5 * d * px, lambda dx, dy, metric=metric: (metric(dx, dy) < 0.92).astype(np.float64), 1.9)
    return np.clip(mask, 0.0, 1.0)


def regolith_base(n: int, metres: float, seed: int, slope_1m: float, inner_m: float) -> np.ndarray:
    """Undulating soil: fBm in metres with the stated RMS slope of its 1 m octave, rolling off below inner_m."""
    f_lo = 1.0
    f_hi = max(2.0, metres / inner_m)
    field = spectral(n, seed, 2.9, f_lo, f_hi)
    k = n / metres
    gx = (np.roll(field, -1, 1) - np.roll(field, 1, 1)) * 0.5 * k
    return field * (slope_1m * 1.6 / (np.sqrt((gx * gx).mean() * 2) + 1e-12))


# Small craters of the lunar surface are in equilibrium: N(> D) = 10^-1.1 D^-2 per square metre (Trask 1966),
# which is 0.12 of the ground per e-fold of diameter, craters on craters at every size. The layers hold 0.09
# (the height authority carries a sparser population of the larger sizes, 0.03 per e-fold, under them).
CRATER_COVER_PER_EFOLD = 0.09


def crater_cover(d_lo: float, d_hi: float) -> float:
    return CRATER_COVER_PER_EFOLD * float(np.log(d_hi / d_lo))


def fine_regolith(scale: int, metres: float) -> Layer:
    """Mature lunar soil. near: powder with grain, cm clods, pits of 2.5-40 cm and pebbles; mid: craterlets of
    0.12-3 m and clods; far: craters of 1-30 m; aerial: craters of 8-250 m. The size ranges of neighbouring
    layers overlap, so that no distance shows craters of one size only; most craters are worn, a few fresh
    and bright. From the mid layer up the relief is the craters' own, on level ground: no swell (a mare is a
    plain), and no rescaling to a wanted slope (that turned the base into ripples)."""
    n = layer_size(scale)
    seed = 700 + scale * 37
    if scale == 0:
        h = regolith_base(n, metres, seed, 0.05, 0.25)
        grain = spectral(n, seed + 1, 1.2, 40, 500) * 0.0011 + spectral(n, seed + 2, 2.0, 6, 60) * 0.0035
        h += grain
        scatter_craters(h, metres, seed + 3, 0.025, 0.4, 0.5 * crater_cover(0.025, 0.4), exponent=2.2, fresh_power=1.5)
        # The soil is cloddy at the centimetre: clumps of a finger's width and less, sharp-edged, a quarter of
        # the ground (each a lit facet with a black sliver behind it under a low sun), and a few stones.
        clods = scatter_lumps(h, metres, seed + 4, 0.008, 0.07, 0.26, 0.6, 0.45)
        stones = scatter_lumps(h, metres, seed + 5, 0.015, 0.09, 0.012, 0.6, 0.9)
        speck = unit(spectral(n, seed + 6, 0.6, 60, 500))
        albedo = tint(GREY, n) * (0.93 + 0.14 * speck)[..., None] * (1.0 - 0.05 * clods)[..., None] * (1.0 + 0.22 * stones)[..., None]
        rough = 0.95 - 0.06 * stones
        return Layer(metres, h, albedo, rough, 1.2).scaled_to_slope(0.27).with_feature_height(n / 12)
    if scale == 1:
        # Fine roughness only (a few millimetres); the forms are the craterlets'.
        h = spectral(n, seed + 1, 1.8, 20, 250) * 0.003
        fresh = scatter_craters(h, metres, seed + 3, 0.12, 3.0, 1.3 * crater_cover(0.12, 3.0), exponent=2.0, fresh_power=2.0)
        # Clods only: stones of this size are meshes of the rock field (a stone in a normal map is a decal that
        # is all lit or all black under a low sun, with no shadow on the ground).
        scatter_lumps(h, metres, seed + 4, 0.06, 0.14, 0.01, 0.3, 0.0)
        h = gauss(h, 0.6)
        mott = unit(spectral(n, seed + 6, 2.0, 2, 40))
        albedo = tint(GREY, n) * (0.95 + 0.10 * mott)[..., None] * (1.0 + 0.10 * fresh)[..., None]
        return Layer(metres, h, albedo, np.full((n, n), 0.95), 1.0).with_feature_height(n / 12)
    d_lo, d_hi = ((1.0, 30.0), (8.0, 250.0))[scale - 2]
    h = np.zeros((n, n))
    fresh = scatter_craters(h, metres, seed + 3, d_lo, d_hi, 1.2 * crater_cover(d_lo, d_hi), exponent=2.0, fresh_power=2.5)
    h = gauss(h, 0.8)
    mott = unit(spectral(n, seed + 6, 2.2, 1, 24))
    albedo = tint(GREY, n) * (0.95 + 0.10 * mott)[..., None] * (1.0 + 0.16 * gauss(fresh, 1.0))[..., None]
    return Layer(metres, h, albedo, np.full((n, n), 0.95), 0.8).with_feature_height(n / 12)


def blocky_ejecta(scale: int, metres: float) -> Layer:
    """Fresh ejecta: angular fragments of many sizes half-buried in soil, brighter than the mature soil."""
    n = layer_size(scale)
    seed = 800 + scale * 41
    lo, hi, cover = ((0.012, 0.16, 0.30), (0.08, 0.3, 0.16), (0.7, 2.0, 0.05), (6.0, 12.0, 0.01))[scale]
    # Undulating soil under the fragments at the two near scales; from the far layer up the ground is
    # level and the relief is the blocks' and the craters' own.
    h = regolith_base(n, metres, seed, 0.06, 0.3 * (1, 4, 20, 160)[scale]) if scale < 2 else np.zeros((n, n))
    h += spectral(n, seed + 1, 1.4, 30, n // 2) * (0.0012, 0.006, 0.01, 0.03)[scale]
    stones = scatter_lumps(h, metres, seed + 2, lo, hi, cover, 0.55, 1.0)
    if scale > 0:
        d_lo, d_hi = ((0.15, 0.7), (1.5, 12.0), (10.0, 120.0))[scale - 1]
        scatter_craters(h, metres, seed + 3, d_lo, d_hi, crater_cover(d_lo, d_hi), fresh_power=1.0)
    facet = unit(spectral(n, seed + 4, 1.0, 8, 200))
    mott = unit(spectral(n, seed + 5, 2.2, 2, 30))
    base = tint((0.128, 0.125, 0.118), n) * (0.92 + 0.16 * mott)[..., None]
    rock = tint((0.150, 0.147, 0.140), n) * (0.85 + 0.35 * facet)[..., None]
    m = gauss(stones, 0.7)[..., None]
    albedo = base * (1 - m) + rock * m
    # (The far and aerial layers have no undulating base that a rescaling could turn into ripples: the blocks'
    # own slopes are scaled, which keeps a field of them from going black under a low sun.)
    return Layer(metres, h, albedo, 0.94 - 0.08 * gauss(stones, 0.7), 1.4).scaled_to_slope((0.32, 0.20, 0.12, 0.08)[scale]).with_feature_height(n / 12)


def compacted_soil(scale: int, metres: float) -> Layer:
    """Compacted, cloddy soil of slopes: a firm lumpy crust, slightly darker than loose soil."""
    n = layer_size(scale)
    seed = 900 + scale * 43
    lo, hi, cover = ((0.01, 0.12, 0.45), (0.07, 0.3, 0.25), (0.6, 2.5, 0.16), (5.0, 20.0, 0.10))[scale]
    # A lumpy crust at the two near scales. Clods of metres do not exist: from the far layer up the slope
    # soil is level ground with worn craters.
    if scale < 2:
        h = regolith_base(n, metres, seed, 0.07, 0.3 * (1, 4)[scale])
        h += spectral(n, seed + 1, 1.6, 30, n // 2) * (0.001, 0.005)[scale]
        clods = scatter_lumps(h, metres, seed + 2, lo, hi, cover, 0.35, 0.15)
    else:
        h = spectral(n, seed + 1, 1.6, 30, n // 2) * (0.01, 0.03)[scale - 2]
        clods = np.zeros((n, n))
        d_lo, d_hi = ((1.0, 14.0), (8.0, 150.0))[scale - 2]
        scatter_craters(h, metres, seed + 3, d_lo, d_hi, crater_cover(d_lo, d_hi), fresh_power=3.0)
    h = gauss(h, 0.5)
    fine = unit(spectral(n, seed + 4, 1.2, 24, n // 2))
    albedo = tint((0.108, 0.105, 0.099), n) * (0.93 + 0.14 * fine)[..., None] * (1.0 - 0.06 * gauss(clods, 1.0))[..., None]
    layer = Layer(metres, h, albedo, np.full((n, n), 0.94), 1.1)
    if scale < 2:
        layer.scaled_to_slope((0.24, 0.15)[scale])
    return layer.with_feature_height(n / 12)


def boulder(scale: int, metres: float) -> Layer:
    """The face of a rock: fracture facets that meet at steps and cracks, zap pits, crystal specks and a film
    of dust in the hollows. Carried by the rock meshes (near layer); the larger layers repeat it coarser."""
    n = layer_size(scale)
    seed = 1000 + scale * 47
    f1, f2, ids, _ = worley(n, 46, seed, jitter=1.0)
    ys, xs = np.mgrid[0:n, 0:n] / n
    # Every facet is a plane of its own tilt and level; they meet in steps along the cell borders.
    gx = (cell_random(ids, seed + 1) - 0.5) * 0.5
    gy = (cell_random(ids, seed + 2) - 0.5) * 0.5
    level = cell_random(ids, seed + 3) * 0.03
    h = (level + gx * (xs - 0.5) * 0.25 + gy * (ys - 0.5) * 0.25) * metres
    h = gauss(h, 1.2)
    edge = f2 - f1
    crack = 1.0 - smoothstep(0.0, 0.05, edge)
    h -= crack * 0.004 * metres
    h += spectral(n, seed + 4, 1.6, 8, n // 2) * 0.0009 * metres
    scatter_craters(h, metres, seed + 5, 0.006 * metres, 0.03 * metres, 0.05, exponent=2.2, fresh_power=1.0)
    shade = 0.84 + 0.32 * cell_random(ids, seed + 6)
    speck = unit(spectral(n, seed + 7, 0.3, 80, n // 2))
    crystals = smoothstep(0.9, 0.98, speck)
    dust = smoothstep(0.4, 1.2, spectral(n, seed + 8, 2.4, 2, 16))
    albedo = tint((0.150, 0.147, 0.140), n) * shade[..., None] * (0.93 + 0.14 * speck)[..., None]
    albedo = albedo * (1.0 - 0.45 * crack)[..., None] * (1.0 + 0.5 * crystals)[..., None]
    albedo = albedo * (1.0 - 0.5 * dust)[..., None] + tint(GREY, n) * (0.5 * dust)[..., None]
    rough = 0.9 - 0.1 * crystals + 0.05 * dust
    return Layer(metres, h, albedo, rough, 1.3).scaled_to_slope((0.30, 0.22, 0.14, 0.08)[scale]).with_feature_height(n / 12)


