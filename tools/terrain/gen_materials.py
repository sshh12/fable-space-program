def bake(layer: Layer) -> tuple[np.ndarray, np.ndarray, dict]:
    """8-bit textures of a layer: albedo+height, normal+roughness+AO, and the statistics the renderer needs."""
    n = layer.height_m.shape[0]
    blend = layer.blend_height()
    relief = float(blend.max()) + 1e-9
    h = blend / relief
    gx, gy = layer.slopes()
    inv = 1.0 / np.sqrt(1.0 + gx * gx + gy * gy)
    nx, ny = -gx * inv, -gy * inv
    # Ambient occlusion from concavity at three scales (a point lower than its surroundings sees less sky),
    # in units of slope: depth below the surroundings over the radius looked at.
    occ = np.zeros_like(h)
    texel = layer.metres / n
    for sigma, w in ((2.0, 0.45), (6.0, 0.35), (18.0, 0.2)):
        occ += w * np.clip(gauss(layer.height_m, sigma) - layer.height_m, 0.0, None) / (sigma * texel)
    ao = np.clip(1.0 - layer.ao_gain * 1.6 * occ, 0.3, 1.0)
    srgb = linear_to_srgb(layer.albedo)
    ah = np.zeros((n, n, 4), np.uint8)
    ah[..., :3] = np.clip(np.round(srgb * 255.0), 0, 255)
    # Height never stores 0, so no encoder may treat a texel as fully transparent.
    ah[..., 3] = np.clip(np.round(h * 254.0) + 1, 1, 255)
    nra = np.zeros((n, n, 4), np.uint8)
    nra[..., 0] = np.clip(np.round((nx * 0.5 + 0.5) * 255.0), 0, 255)
    nra[..., 1] = np.clip(np.round((ny * 0.5 + 0.5) * 255.0), 0, 255)
    nra[..., 2] = np.clip(np.round(layer.roughness * 255.0), 0, 255)
    nra[..., 3] = np.clip(np.round(ao * 255.0), 1, 255)
    stats = {
        "reliefM": round(relief, 5),
        "rmsSlope": round(layer.rms_slope(), 4),
        "meanRoughness": round(float(nra[..., 2].mean() / 255.0), 4),
        "meanHeight": round(float(ah[..., 3].mean() / 255.0), 4),
    }
    return ah, nra, stats


def decoded_mean(path: str) -> list[float]:
    """Mean linear albedo of an albedo file as the renderer will decode it."""
    back = np.asarray(Image.open(path).convert("RGBA"), np.float64)[..., :3] / 255.0
    return [round(float(v), 5) for v in srgb_to_linear(back).reshape(-1, 3).mean(0)]


def preview(ah: np.ndarray, nra: np.ndarray, sun_elevation_deg: float) -> np.ndarray:
    """Lit preview, tiled 2 x 2 and reduced to 512 px: Lambert under a low sun plus ambient, AO applied."""
    nx = nra[..., 0] / 255.0 * 2 - 1
    ny = nra[..., 1] / 255.0 * 2 - 1
    nz = np.sqrt(np.clip(1 - nx * nx - ny * ny, 0.04, 1))
    el = np.radians(sun_elevation_deg)
    sun = np.array([np.cos(el) * 0.76, np.cos(el) * 0.65, np.sin(el)])
    lambert = np.clip(nx * sun[0] + ny * sun[1] + nz * sun[2], 0, None) / np.sin(el)
    lin = srgb_to_linear(ah[..., :3] / 255.0)
    lit = lin * (lambert[..., None] * 0.8 + 0.25 * (nra[..., 3] / 255.0)[..., None]) / lin.reshape(-1, 3).mean() * 0.16
    img = np.clip(linear_to_srgb(np.clip(lit, 0, 1)) * 255, 0, 255).astype(np.uint8)
    # Left: two repeats each way, reduced. Right: a 512 px crop at full resolution.
    tiled = np.tile(img, (2, 2, 1))
    return np.concatenate([cv2.resize(tiled, (512, 512), interpolation=cv2.INTER_AREA), tiled[:512, :512]], 1)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--set", choices=sorted(SETS), action="append")
    ap.add_argument("--preview", action="store_true")
    ap.add_argument("--manifest-only", action="store_true")
    args = ap.parse_args()
    for set_id in args.set or sorted(SETS):
        spec = SETS[set_id]
        out_dir = os.path.join(REPO, "public", "assets", "terrain", set_id)
        os.makedirs(out_dir, exist_ok=True)
        if args.manifest_only:
            with open(os.path.join(out_dir, "set.json"), "r", encoding="utf-8") as f:
                manifest = json.load(f)
            if [m["id"] for m in manifest["materials"]] != [m[0] for m in spec["materials"]]:
                raise SystemExit(f"{set_id}: the materials of set.json are not those of this script; build the textures")
            for key in MANIFEST_KEYS:
                manifest[key] = spec[key]
            with open(os.path.join(out_dir, "set.json"), "w", encoding="utf-8", newline="\n") as f:
                json.dump(manifest, f, indent=2)
                f.write("\n")
            print(f"{set_id}: set.json rewritten")
            continue
        for old in os.listdir(out_dir):
            # (The leaf atlas of the ground cover is gen_foliage.py's.)
            if old.endswith(".webp") and not old.startswith("foliage"):
                os.remove(os.path.join(out_dir, old))
        materials = []
        sheets = []
        total = 0
        for mat_id, make in spec["materials"]:
            layers = []
            row = []
            for scale in range(len(SCALE_NAMES)):
                layer, seam = make(scale, spec["scalesM"][scale])
                ah, nra, stats = bake(layer)
                ah_name, nra_name = f"{mat_id}-{SCALE_NAMES[scale]}.ah.webp", f"{mat_id}-{SCALE_NAMES[scale]}.nra.webp"
                ah_path, nra_path = os.path.join(out_dir, ah_name), os.path.join(out_dir, nra_name)
                # Colour compresses lossily (the height in alpha stays exact); normals never do: chroma
                # subsampling would mix their two axes.
                Image.fromarray(ah, "RGBA").save(ah_path, "WEBP", lossless=False, quality=90, alpha_quality=100, method=6, exact=True)
                Image.fromarray(nra, "RGBA").save(nra_path, "WEBP", lossless=True, quality=100, method=6, exact=True)
                back = np.asarray(Image.open(nra_path).convert("RGBA"))
                if not np.array_equal(back, nra):
                    raise SystemExit(f"{nra_name}: lossless round trip failed")
                back = np.asarray(Image.open(ah_path).convert("RGBA"))
                if not np.array_equal(back[..., 3], ah[..., 3]):
                    raise SystemExit(f"{ah_name}: the height channel did not survive encoding")
                size = os.path.getsize(ah_path) + os.path.getsize(nra_path)
                total += size
                mean = decoded_mean(ah_path)
                layers.append({"albedoHeight": ah_name, "normalRoughAo": nra_name, "meanAlbedo": mean, "meanRoughness": stats["meanRoughness"], "reliefM": stats["reliefM"], "meanHeight": stats["meanHeight"]})
                print(f"{set_id}/{mat_id}-{SCALE_NAMES[scale]}: mean albedo {mean}, roughness {stats['meanRoughness']}, rms slope {stats['rmsSlope']}, relief {stats['reliefM'] * 100:.2f} cm, "
                      f"wrap step / inner step {seam:.2f}, {size // 1024} KB")
                if args.preview:
                    row.append(preview(ah, nra, 35.0 if spec["photo"] else 12.0))
            materials.append({"id": mat_id, "layers": layers})
            if args.preview:
                sheets.append(np.concatenate(row, 1))
        manifest = {"formatVersion": 2, "id": set_id, "nearSize": NEAR_SIZE, "wideSize": WIDE_SIZE, "scalesM": spec["scalesM"], "materials": materials}
        for key in MANIFEST_KEYS:
            manifest[key] = spec[key]
        with open(os.path.join(out_dir, "set.json"), "w", encoding="utf-8", newline="\n") as f:
            json.dump(manifest, f, indent=2)
            f.write("\n")
        print(f"{set_id}: {total / 2 ** 20:.1f} MiB of textures")
        if args.preview:
            prev_dir = os.path.join(REPO, "out", "terrain", "materials")
            os.makedirs(prev_dir, exist_ok=True)
            for i, sheet in enumerate(sheets):
                Image.fromarray(sheet).save(os.path.join(prev_dir, f"{set_id}-{spec['materials'][i][0]}.png"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
