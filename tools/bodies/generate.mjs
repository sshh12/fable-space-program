#!/usr/bin/env node
// Generates the staged body library from the source tables (tools/bodies/sources) and the live v1 Earth, Moon
// and Sun files (read only):
//
//   data/staged/bodies/<id>.json              one BodyDef per body of ARCHITECTURE 8.1 (32)
//   data/staged/terrain/<id>.terrain.json     the terrain section of each new solid body (25)
//   data/staged/bodies/radii.json             id, mean, equatorial and polar radius (m) per body
//   tools/bodies/provenance.json              the source (URL, time of retrieval) and derivation of every value
//   tests/unit/bodies/stagedBodies.generated.ts   the same files as typed TypeScript literals (the typed fixture)
//
//   node tools/bodies/generate.mjs           write them
//   node tools/bodies/generate.mjs --check   fail (exit 1) when any file on disk differs from what would be written
//
// No network: refresh the sources with fetch-sources.mjs. data/defs is never written.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { BODY_ORDER } from './lib/catalogue.mjs';
import { buildLibrary } from './lib/build.mjs';
import { formatJson } from './lib/format.mjs';
import { REPO_ROOT } from './lib/http.mjs';
import { LOBBY_EPOCH_UT } from './lib/orbits.mjs';
import { loadBake, loadLive, loadSources } from './lib/sources.mjs';

export const STAGED_BODIES = 'data/staged/bodies';
export const STAGED_TERRAIN = 'data/staged/terrain';
export const FIXTURE = 'tests/unit/bodies/stagedBodies.generated.ts';
export const PROVENANCE = 'tools/bodies/provenance.json';

export function generateFiles() {
  const lib = buildLibrary(loadSources(), loadLive(), loadBake());
  const files = new Map();
  for (const id of BODY_ORDER) {
    const b = lib.bodies[id];
    files.set(`${STAGED_BODIES}/${id}.json`, b.text ?? formatJson(b.json));
  }
  for (const [id, t] of Object.entries(lib.terrain)) files.set(`${STAGED_TERRAIN}/${id}.terrain.json`, formatJson(t));
  files.set(`${STAGED_BODIES}/radii.json`, formatJson({ description: 'Radii of the staged bodies, m: meanRadius = BodyDef.radius (the datum sphere), equatorialRadius and polarRadius = pck00011 a and c, radiiAbc = the pck00011 triaxial radii. Cross-checked by planet-bake and bodies-activation.', bodies: lib.radii }));
  files.set(PROVENANCE, formatJson({ generatedBy: 'tools/bodies/generate.mjs', lobbyEpochUt: LOBBY_EPOCH_UT, paths: lib.paths, provenance: lib.provenance }));
  files.set(FIXTURE, fixtureSource(lib));
  return files;
}

function fixtureSource(lib) {
  const bodies = BODY_ORDER.map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(lib.bodies[id].json)},`).join('\n');
  const terrain = Object.entries(lib.terrain).map(([id, t]) => `  ${JSON.stringify(id)}: ${JSON.stringify(t)},`).join('\n');
  return `// Generated by tools/bodies/generate.mjs from the same data as data/staged: do not edit (run the generator).
// The staged body files as typed literals: \`satisfies\` makes the compiler check every generated field against
// the v2 body contract (src/core/contracts/defs.ts), discriminated unions and excess properties included.
import type { BodyDef, BodyRenderDef, BodyTerrainDef, TerrainAmplificationDef } from '../../../src/core/contracts/defs';

/** A section reference as written in a definition file ({ "$ref": path relative to the file, inside its root }). */
export interface DefRef {
  $ref: string;
  optional?: true;
}

/**
 * A staged body file: BodyDef with sections that may be references (the terrain section, the amplification of a
 * terrain section, the render sections) and with \`warpAltitudeLimits\` optional, as ARCHITECTURE 8.3 and the
 * contract's own comment specify (absent = defaults from the radius and the atmosphere top, once the warp
 * table has nine rails levels). Nothing else is relaxed.
 */
export type StagedBodyFile = Omit<BodyDef, 'warpAltitudeLimits' | 'terrain' | 'render'> & {
  warpAltitudeLimits?: number[];
  terrain: DefRef | (Omit<BodyTerrainDef, 'amplification'> & { amplification: TerrainAmplificationDef | DefRef }) | null;
  render: Omit<BodyRenderDef, 'surface' | 'atmosphere' | 'clouds' | 'ocean'> & {
    surface: BodyRenderDef['surface'] | DefRef;
    atmosphere: BodyRenderDef['atmosphere'] | DefRef;
    clouds: BodyRenderDef['clouds'] | DefRef;
    ocean: BodyRenderDef['ocean'] | DefRef;
  };
};

export interface RadiiRow {
  id: string;
  meanRadius: number;
  equatorialRadius: number;
  polarRadius: number;
  radiiAbc: [number, number, number];
}

export const STAGED_BODY_FILES = {
${bodies}
} satisfies Record<string, StagedBodyFile>;

export const STAGED_TERRAIN_FILES = {
${terrain}
} satisfies Record<string, BodyTerrainDef>;

export const STAGED_RADII = ${JSON.stringify(lib.radii)} satisfies RadiiRow[];
`;
}

function main() {
  const check = process.argv.includes('--check');
  const files = generateFiles();
  const stale = [];
  for (const [rel, content] of files) {
    const abs = join(REPO_ROOT, rel);
    const old = existsSync(abs) ? readFileSync(abs, 'utf8') : null;
    if (old === content) continue;
    if (check) {
      stale.push(rel);
      continue;
    }
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, content);
    console.log(`wrote ${relative(REPO_ROOT, abs).replace(/\\/g, '/')}`);
  }
  if (check) {
    if (stale.length) {
      console.error(`generate --check: ${stale.length} file(s) differ from the generator's output:\n  ${stale.join('\n  ')}\nRun node tools/bodies/generate.mjs and review the diff.`);
      process.exit(1);
    }
    console.log(`generate --check: ${files.size} files up to date`);
  }
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, '/').split('/').pop())) main();
